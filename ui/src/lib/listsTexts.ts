const TEXTS: Record<Lang, Record<ListsKey, string>> = { en: EN, de: DE };

/** Whether `key` is a word of this chunk. */
export function isListsKey(key: string): key is ListsKey {
  return Object.hasOwn(EN, key);
}

/** The word `key` in `lang`, with `{name}` filled from `params`. */
export function listsText(lang: Lang, key: ListsKey, params: Record<string, string | number> = {}): string {
  return TEXTS[lang][key].replace(/\{(\w+)\}/g, (all, name: string) => (Object.hasOwn(params, name) ? String(params[name]) : all));
}

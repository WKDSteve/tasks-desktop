/** Whether `key` is a word of the map (else one of the page, `i18n`). */
export function isPathMapKey(key: string): key is PathMapKey {
  return Object.hasOwn(EN, key);
}

export function pathMapText(lang: Lang, key: PathMapKey, params: Record<string, string | number> = {}): string {
  const text: string = lang === 'de' ? DE[key] : EN[key];
  return text.replace(/\{(\w+)\}/g, (all, k: string) => (k in params ? String(params[k]) : all));
}
